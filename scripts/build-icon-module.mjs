// Compiles src/icons/*.svg (Lucide, ISC license) into src/lib/icon-data.ts.
// Add an icon: download https://cdn.jsdelivr.net/npm/lucide-static@1.52.0/icons/<name>.svg into src/icons, then run
//   node scripts/build-icon-module.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';

const dir = 'src/icons';
const files = (await readdir(dir)).filter((f) => f.endsWith('.svg')).sort();
const entries = [];
for (const file of files) {
  const svg = await readFile(`${dir}/${file}`, 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  entries.push(`  '${file.replace(/\.svg$/, '')}': '${inner.replace(/'/g, "\\'")}',`);
}

const out = `// Generated by scripts/build-icon-module.mjs from src/icons. Do not edit by hand.
// Icons: Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Contributors.
export const ICONS: Record<string, string> = {
${entries.join('\n')}
};
`;
await writeFile('src/lib/icon-data.ts', out);
console.log(`Wrote ${entries.length} icons to src/lib/icon-data.ts`);
